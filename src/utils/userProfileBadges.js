function 取得量級目前可取得成就(量級, 目前時間戳記) {
  // 截止當下仍能取得該階級，因此使用 <=。時限成就依首週、次週排序，第一個
  // 尚未截止的項目就是未取得玩家目前應追蹤的最高階目標。
  const 時限成就 = 量級.時限徽章.find((成就) => {
    const 截止時間戳記 = new Date(成就.截止時間Iso).getTime();
    return Number.isFinite(截止時間戳記) && 目前時間戳記 <= 截止時間戳記;
  });
  if (時限成就) {
    return 時限成就;
  }

  // null 表示目前仍限制依序攻略樓層，末層通關可持續取得「踏破」。已設定切點
  // 的量級則只在切點當下以前顯示踏破；超過後改為顯示四層皆有效的「通關」。
  if (量級.末層可代表全層截止時間Iso === null) {
    return 量級.踏破徽章;
  }
  const 踏破截止時間戳記 = new Date(量級.末層可代表全層截止時間Iso).getTime();
  return Number.isFinite(踏破截止時間戳記) && 目前時間戳記 <= 踏破截止時間戳記
    ? 量級.踏破徽章
    : 量級.通關徽章;
}

/**
 * 依角色已取得階級與目前時間，選出每個零式量級目前適用的一項。
 *
 * 全站成就索引與手冊零式分頁都保留四階完整統計；呼叫端只用這份結果標記
 * 玩家已取得的階級，或完全未取得時仍可追蹤的最高階目標。這能完整比較各階
 * 人數，同時避免 Vue 重新實作截止時間與互斥優先序。
 */
export function 篩選成就手冊適用成就(
  成就目錄,
  已獲得成就Ids = [],
  目前時間戳記 = Date.now(),
) {
  const 目錄 = Array.isArray(成就目錄) ? 成就目錄 : [];
  const 已獲得成就Id集合 = 已獲得成就Ids instanceof Set
    ? 已獲得成就Ids
    : new Set(Array.isArray(已獲得成就Ids) ? 已獲得成就Ids : []);
  const 數字時間戳記 = Number(目前時間戳記);
  const 有效目前時間戳記 = Number.isFinite(數字時間戳記) ? 數字時間戳記 : Date.now();
  const 全部量級成就Ids = new Set();
  const 適用量級成就Ids = new Set();

  for (const 量級 of 零式量級成就定義) {
    const 階級成就 = 取得量級成就階級(量級);
    for (const 成就 of 階級成就) {
      全部量級成就Ids.add(成就.id);
    }

    // 正常資料只會有一個已取得階級；若舊資料曾同時保存多個 ID，仍依首週、
    // 次週、踏破、通關的固定優先序只選取最高階，避免互斥進度與目前目標重疊。
    const 已取得階級 = 階級成就.find((成就) => 已獲得成就Id集合.has(成就.id));
    const 適用成就 = 已取得階級 || 取得量級目前可取得成就(量級, 有效目前時間戳記);
    if (適用成就?.id) {
      適用量級成就Ids.add(適用成就.id);
    }
  }

  return 目錄.filter((成就) => (
    !全部量級成就Ids.has(成就?.id) || 適用量級成就Ids.has(成就.id)
  ));
}

function 轉為有限整數(數值, 預設值 = 0) {
  const 結果 = Number(數值);
  return Number.isFinite(結果) ? Math.trunc(結果) : 預設值;
}

function 建立次數索引(成績列表, 取得鍵值) {
  const 索引 = new Map();
  for (const 成績 of Array.isArray(成績列表) ? 成績列表 : []) {
    const 鍵值 = 取得鍵值(成績);
    if (!鍵值) {
      continue;
    }
    索引.set(鍵值, (索引.get(鍵值) || 0) + 1);
  }
  return 索引;
}

function 取得達標種類數(次數索引, 最低次數) {
  return Array.from(次數索引.values()).filter((次數) => 次數 >= 最低次數).length;
}

function 取得成績開始時間戳記(成績) {
  const Iso時間 = String(成績?.recorded_at_iso || "").trim();
  if (Iso時間) {
    const Iso時間戳記 = new Date(Iso時間).getTime();
    if (Number.isFinite(Iso時間戳記)) {
      return Iso時間戳記;
    }
  }

  // `recorded_at_iso` 是目前個人成績檔的正式欄位；數字時間只作為舊資料的
  // 向後相容 fallback。缺少或無法解析時間時不能猜測任何限時踏破，但四層
  // 皆有有效版本成績時仍可取得不依時間判定的「通關」。
  const 數字時間戳記 = Number(成績?.recorded_at);
  return Number.isFinite(數字時間戳記) && 數字時間戳記 > 0 ? 數字時間戳記 : null;
}

function 取得通關完成時間戳記(成績) {
  const 開始時間戳記 = 取得成績開始時間戳記(成績);
  if (開始時間戳記 === null) {
    return null;
  }

  // FFLogs 的 `recorded_at_iso` 對應 fight 開始時間；成就門檻描述的是「完成
  // 通關」的時間，因此必須加上 clear time。若舊資料缺少戰鬥時間，寧可回退
  // 到「通關」的四層條件，也不能只用開始時間誤判任何限時門檻。
  const 通關時間毫秒原始值 = 成績?.clear_time_ms;
  if (通關時間毫秒原始值 !== null && 通關時間毫秒原始值 !== undefined) {
    const 通關時間毫秒 = Number(通關時間毫秒原始值);
    if (Number.isFinite(通關時間毫秒) && 通關時間毫秒 >= 0) {
      return 開始時間戳記 + 通關時間毫秒;
    }
  }
  const 通關時間秒數原始值 = 成績?.clear_time_seconds;
  if (通關時間秒數原始值 !== null && 通關時間秒數原始值 !== undefined) {
    const 通關時間秒數 = Number(通關時間秒數原始值);
    if (Number.isFinite(通關時間秒數) && 通關時間秒數 >= 0) {
      return 開始時間戳記 + 通關時間秒數 * 1000;
    }
  }
  return null;
}

function 建立有效版本成績副本索引(公開成績) {
  const 副本索引 = new Map();
  for (const 成績 of Array.isArray(公開成績) ? 公開成績 : []) {
    if (成績?.is_obsolete_record || !成績?.encounter_key) {
      continue;
    }
    const 副本成績 = 副本索引.get(成績.encounter_key) || [];
    副本成績.push(成績);
    副本索引.set(成績.encounter_key, 副本成績);
  }
  return 副本索引;
}

function 是否在截止時間前通關末層(量級, 有效版本成績副本索引, 截止時間Iso) {
  const 截止時間戳記 = new Date(截止時間Iso).getTime();
  if (!量級.末層副本鍵值 || !Number.isFinite(截止時間戳記)) {
    return false;
  }

  // 首週、次週與「解除樓層限制前」的踏破都只看量級末層，因為該期間能
  // 通關末層就代表先前樓層已完成，不應因較早樓層沒有公開 Log 而降級。
  // 「截止前」包含門檻當下，所以使用 <=；若同一末層有多次紀錄，任一筆符合
  // 即可，避免後續重刷留下較晚紀錄後反而失去既有成就。
  return (有效版本成績副本索引.get(量級.末層副本鍵值) || []).some((成績) => {
    const 通關完成時間戳記 = 取得通關完成時間戳記(成績);
    return 通關完成時間戳記 !== null && 通關完成時間戳記 <= 截止時間戳記;
  });
}

function 是否符合量級踏破(量級, 有效版本成績副本索引) {
  const 末層成績 = 有效版本成績副本索引.get(量級.末層副本鍵值) || [];
  const 末層代表截止時間Iso = 量級.末層可代表全層截止時間Iso;

  // 尚未解除樓層攻略順序限制時，能通關末層就必然已完成前層，不需要另外找到
  // 每一層的公開 Log。以 null 明確表示此狀態，未來公告解除時間後只需填入切點。
  if (末層成績.length > 0 && 末層代表截止時間Iso === null) {
    return true;
  }

  // 已知解除時間的量級，只允許切點當下以前完成的末層取得「踏破」。切點後
  // 即使四層都有公開成績，也只能改由下一階的「通關」條件判定，不能回補踏破。
  if (
    末層成績.length > 0
    && 是否在截止時間前通關末層(
      量級,
      有效版本成績副本索引,
      末層代表截止時間Iso,
    )
  ) {
    return true;
  }

  return false;
}

function 是否符合量級通關(量級, 有效版本成績副本索引) {
  return 量級.副本鍵值.every((副本鍵值) => 有效版本成績副本索引.has(副本鍵值));
}

function 是否符合量級炒股仔(量級, 有效版本成績副本索引) {
  // PR 是資料建置層以「同副本、同職業、Active 達標」的 rDPS 樣本算出；
  // `qualified` 必須為 true，避免 Active 不足或過版紀錄被 rank fallback 誤收。
  // 各層只要求任一筆達標紀錄，不要求同一職業，符合玩家確認的跨職判定口徑。
  return 量級.副本鍵值.every((副本鍵值) => (
    (有效版本成績副本索引.get(副本鍵值) || []).some((成績) => {
      if (成績?.performance?.qualified !== true) {
        return false;
      }
      const PR值 = 計算PR值(成績.performance);
      // 個人成績單目前把 PR 四捨五入為整數顯示及著色；成就沿用相同口徑，
      // 避免畫面已顯示 PR 95，玩家卻因未四捨五入值為 94.xx 而無法取得。
      return PR值 !== null && Math.round(PR值) >= 個人成績徽章門檻.炒股仔最低顯示PR;
    })
  ));
}

function 建立徽章顯示資料(成就) {
  return {
    id: 成就.id,
    名稱: 成就.名稱,
    說明: 成就.說明,
    分類: 成就.分類,
    樣式類別: 成就.樣式類別,
  };
}

function 取得排序後零式量級() {
  // 顯示優先序是產品定義，不可依副本開放日期或名稱自動推測。數字對應整個
  // 成就區的難度位置：次重量級第二、輕量級第三；第一保留給六絕全通稱號。
  return Array.from(零式量級成就定義)
    .sort((前一量級, 後一量級) => 前一量級.顯示優先序 - 後一量級.顯示優先序);
}

function 建立單一量級踏破徽章(量級, 有效版本成績副本索引) {
  // 每個量級只回傳最高階的一枚：首週、次週、踏破、通關依序判定。踏破在
  // 尚未解除樓層攻略順序限制時可由末層直接證明；通關則永遠要求四層皆有
  // 有效版本公開成績，且只在前三階皆未命中時發放。
  const 時限徽章 = 量級.時限徽章.find((徽章) => (
    是否在截止時間前通關末層(量級, 有效版本成績副本索引, 徽章.截止時間Iso)
  ));
  if (時限徽章) {
    return 建立徽章顯示資料(時限徽章);
  }
  if (是否符合量級踏破(量級, 有效版本成績副本索引)) {
    return 建立徽章顯示資料(量級.踏破徽章);
  }
  if (是否符合量級通關(量級, 有效版本成績副本索引)) {
    return 建立徽章顯示資料(量級.通關徽章);
  }
  return null;
}

/**
 * 依固定副本集合建立量級踏破徽章。
 */
export function 建立零式量級踏破徽章(公開成績) {
  // 量級踏破表達的是該量級仍屬現行難度時的完成度。過版後同一角色可能因
  // 裝備品級、可跳過機制而取得新的公開紀錄，不能反過來補發現行量級成就；
  // 因此只採用資料建置層已標記為非 obsolete 的有效版本通關。
  const 有效版本成績副本索引 = 建立有效版本成績副本索引(公開成績);
  return 取得排序後零式量級()
    .map((量級) => 建立單一量級踏破徽章(量級, 有效版本成績副本索引))
    .filter(Boolean);
}

/**
 * 依固定量級四層與本站顯示 PR 建立炒股仔徽章。
 */
export function 建立零式量級炒股仔徽章(公開成績) {
  const 有效版本成績副本索引 = 建立有效版本成績副本索引(公開成績);
  return 取得排序後零式量級()
    .filter((量級) => 是否符合量級炒股仔(量級, 有效版本成績副本索引))
    .map((量級) => 建立徽章顯示資料(量級.炒股仔徽章));
}

function 建立零式量級成就徽章(公開成績) {
  const 有效版本成績副本索引 = 建立有效版本成績副本索引(公開成績);
  return 取得排序後零式量級().flatMap((量級) => {
    const 踏破徽章 = 建立單一量級踏破徽章(量級, 有效版本成績副本索引);
    const 炒股仔徽章 = 是否符合量級炒股仔(量級, 有效版本成績副本索引)
      ? 建立徽章顯示資料(量級.炒股仔徽章)
      : null;
    // 同量級先顯示完成進度，再顯示額外的分位成就；量級整體仍依
    // 次重量級 → 輕量級排序，讓新增徽章不破壞既有難度優先序。
    return [踏破徽章, 炒股仔徽章].filter(Boolean);
  });
}

/**
 * 依固定六個絕本建立歷史全通稱號。
 */
export function 建立六絕踏破稱號徽章(公開成績) {
  // 此稱號紀念角色曾完成所有已定義絕本，不是用來描述當前版本的零式進度；
  // 因此刻意保留過版公開紀錄。有效版本限制只適用於「量級踏破」這種現行
  // 零式難度成就，不能讓改版後的資料狀態抹去既有的六絕完成事實。
  const 公開通關副本 = new Set(
    (Array.isArray(公開成績) ? 公開成績 : [])
      .map((成績) => 成績?.encounter_key)
      .filter(Boolean),
  );
  if (!六絕踏破副本鍵值.every((副本鍵值) => 公開通關副本.has(副本鍵值))) {
    return [];
  }
  return [{ ...六絕踏破成就 }];
}

/**
 * 建立個人成績單一般模式顯示的成就徽章。
 *
 * 呼叫端必須傳入未套用任何頁面篩選的所有公開成績，並傳入資料建置層計算的
 * `summary.teammate_count`。後者是完整的不同同場玩家數；`frequent_teammates`
 * 僅為首屏效能保留前 20 位，不能拿來判定 50 位玩家的社群核心門檻。
 */
export function 建立個人成績徽章({
  角色名稱 = "",
  公開成績 = [],
  公開同場玩家數 = 0,
  最後紀錄時間 = null,
  近期動態基準時間 = null,
  顯示作者徽章 = false,
  是網站作者 = () => false,
  作者說明 = "",
  取得職能代碼 = () => "",
} = {}) {
  const 成績列表 = Array.isArray(公開成績) ? 公開成績 : [];
  const 徽章 = [];
  const 職業次數 = 建立次數索引(成績列表, (成績) => 成績?.job);
  const 職能次數 = 建立次數索引(成績列表, (成績) => 取得職能代碼(成績?.job));
  const 達標職業數 = 取得達標種類數(職業次數, 個人成績徽章門檻.每職業通關次數);
  const 達標職能數 = 取得達標種類數(職能次數, 個人成績徽章門檻.每職業通關次數);
  const 同場玩家數 = Math.max(0, 轉為有限整數(公開同場玩家數));
  const 最後紀錄時間戳記 = new Date(最後紀錄時間 || 0).getTime();
  const 基準時間戳記 = Number(近期動態基準時間);

  // 網站作者是唯一角色識別，不參與成就難度比較，因此固定置於所有徽章
  // 最前方；六絕全通則是一般成就中的最高難度，緊接在作者識別之後。
  if (顯示作者徽章 && 是網站作者(角色名稱)) {
    // 作者標示是唯一角色身分，不屬於所有玩家都能挑戰的成就，因此不會列入
    // 成就手冊或全站獲得率；`是成就: false` 讓呼叫端不必依名稱猜測語意。
    徽章.push({
      id: "site-author-identity",
      名稱: "網站作者",
      說明: 作者說明,
      樣式類別: "作者徽章",
      是成就: false,
    });
  }

  徽章.push(...建立六絕踏破稱號徽章(成績列表));

  // 量級工具已依產品優先序回傳「次重量級 → 輕量級」，並把各量級的額外
  // 分位成就放在踏破進度之後；Vue 只需依序渲染，不重做名稱判斷或排序。
  徽章.push(...建立零式量級成就徽章(成績列表));

  if (達標職業數 >= 個人成績徽章門檻.多職玩家職業數) {
    徽章.push({
      ...一般個人成績成就.多職玩家,
      說明: `${達標職業數} 個職業各有至少 ${個人成績徽章門檻.每職業通關次數} 場公開通關紀錄`,
    });
  }
  if (達標職能數 >= 個人成績徽章門檻.三色豆職能數) {
    徽章.push({
      ...一般個人成績成就.三色豆,
      說明: `${達標職能數} 種職能各有至少 ${個人成績徽章門檻.每職業通關次數} 場公開通關紀錄`,
    });
  }
  if (成績列表.length >= 個人成績徽章門檻.高活躍公開成績數) {
    徽章.push({ ...一般個人成績成就.高活躍, 說明: `公開成績 ${成績列表.length} 筆` });
  }
  if (同場玩家數 >= 個人成績徽章門檻.社群核心同場玩家數) {
    徽章.push({ ...一般個人成績成就.社群核心, 說明: `與 ${同場玩家數} 位玩家有公開同場紀錄` });
  }
  if (
    Number.isFinite(最後紀錄時間戳記)
    && 最後紀錄時間戳記 > 0
    && Number.isFinite(基準時間戳記)
    && 基準時間戳記 > 0
    && 最後紀錄時間戳記 >= 基準時間戳記 - 7 * 24 * 60 * 60 * 1000
  ) {
    徽章.push({ ...一般個人成績成就.近期活躍, 說明: "近七天內有公開紀錄" });
  }

  return 徽章;
}
